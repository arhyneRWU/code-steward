"""Measure how far into the ranking the gold set can actually see.

The headline numbers in `docs/similarity.md` are reported at depth 30,
which was a *labelling* choice: deep enough to clear 150 pairs,
shallow enough that one person could read every pair properly. It is
tempting to read a deeper slice of the same ranking and report the
better recall that comes with it.

That does not work, and this module exists to show why rather than to
leave it as an assertion. Past the pool depth an arm returns pairs
nobody judged, so its precision is computed over a shrinking labelled
fraction of its own output. The unlabelled share and the pessimistic
precision are reported alongside every row, and they are what make the
deep rows uninterpretable.

The second measurement here is the detection floor: how many labelled
positives share too few windows for the arm to see them at any depth.
That number bounds the reimplementation blind spot -- with a large
caveat recorded in the docs, since the pool that produced these labels
was partly generated by the arm being measured.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from benchmarks.similarity.corpus import CORPORA, corpus_files
from benchmarks.similarity.units import load_units
from code_steward.similarity import MIN_SHARED_SHINGLES, jaccard, rank_all_pairs, shingles

POSITIVE_LABELS = frozenset({"same-behaviour", "overlapping"})
DEPTHS = (10, 30, 60, 120, 240, 480)

# The depth the pool was built at. At or below it every returned pair
# is labelled; above it the numbers stop meaning anything.
POOL_DEPTH = 30


def _labels(path: Path) -> dict[str, dict[tuple[str, str], str]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    grouped: dict[str, dict[tuple[str, str], str]] = {}
    for row in payload["pairs"]:
        left, right = row["left"], row["right"]
        key = (left, right) if left < right else (right, left)
        grouped.setdefault(row["corpus"], {})[key] = row["label"]
    return grouped


def detection_floor(
    prepared: dict[str, dict[str, frozenset[int]]],
    labels: dict[str, dict[tuple[str, str], str]],
) -> dict[str, Any]:
    """Count labelled positives the arm cannot see at any depth."""
    invisible = 0
    total = 0
    overlaps: list[float] = []
    for corpus, rows in labels.items():
        for (left, right), label in rows.items():
            if label not in POSITIVE_LABELS:
                continue
            first = prepared[corpus].get(left)
            second = prepared[corpus].get(right)
            if first is None or second is None:
                continue
            total += 1
            overlaps.append(jaccard(first, second))
            if len(first & second) < MIN_SHARED_SHINGLES:
                invisible += 1
    overlaps.sort()
    return {
        "positives_checked": total,
        "invisible_at_any_depth": invisible,
        "median_overlap": round(overlaps[len(overlaps) // 2], 3) if overlaps else 0.0,
        "p10_overlap": round(overlaps[len(overlaps) // 10], 3) if overlaps else 0.0,
    }


def depth_curve(
    prepared: dict[str, dict[str, frozenset[int]]],
    labels: dict[str, dict[tuple[str, str], str]],
) -> list[dict[str, Any]]:
    """Score the arm at each depth, counting what it cannot score."""
    rows = []
    for depth in DEPTHS:
        hits = misses = unlabelled = returned = 0
        for corpus, values in prepared.items():
            known = labels.get(corpus, {})
            for left, right, _ in rank_all_pairs(values, depth):
                returned += 1
                label = known.get((left, right))
                if label is None:
                    unlabelled += 1
                elif label in POSITIVE_LABELS:
                    hits += 1
                else:
                    misses += 1
        judged = hits + misses
        rows.append(
            {
                "depth": depth,
                "returned": returned,
                "labelled": judged,
                "unlabelled": unlabelled,
                "unlabelled_share": round(unlabelled / returned, 3) if returned else 0.0,
                "precision_over_labelled": round(hits / judged, 3) if judged else 0.0,
                "precision_pessimistic": round(hits / returned, 3) if returned else 0.0,
                # Only rows at or below the pool depth mean anything.
                "interpretable": depth <= POOL_DEPTH,
            }
        )
    return rows


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Measure the gold set's usable depth.")
    parser.add_argument("--checkouts", type=Path, required=True)
    parser.add_argument(
        "--labels",
        type=Path,
        default=Path("benchmarks/similarity/reuse_pair_labels.json"),
    )
    parser.add_argument("--output", type=Path, required=True)
    return parser


def main() -> None:
    args = _parser().parse_args()
    labels = _labels(args.labels.resolve())
    prepared: dict[str, dict[str, frozenset[int]]] = {}
    for corpus in CORPORA:
        checkout = (args.checkouts / corpus.name).resolve()
        units = load_units(corpus.name, checkout, corpus_files(corpus, checkout))
        prepared[corpus.name] = {unit.unit_id: shingles(unit.tokens) for unit in units}

    payload = {
        "schema_version": 1,
        "pool_depth": POOL_DEPTH,
        "detection_floor": detection_floor(prepared, labels),
        "depth_curve": depth_curve(prepared, labels),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(payload, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
